def bubble_sort_lexicographic(arr):
    n = len(arr)
    for i in range(n):
        swapped = False
        for j in range(0, n-i-1):
            if arr[j] > arr[j+1]:
                arr[j], arr[j+1] = arr[j+1], arr[j]
                swapped = True
        if not swapped:
            break
    return arr

def selection_sort_lexicographic(arr):
    n = len(arr)
    for i in range(n):
        min_idx = i
        for j in range(i+1, n):
            if arr[j] < arr[min_idx]:
                min_idx = j
        arr[i], arr[min_idx] = arr[min_idx], arr[i]
    return arr

# main
arr = ["banana", "apple", "cherry", "date", "fig", "grape"]
print("Bubble Sort Lexicographic:", bubble_sort_lexicographic(arr.copy()))
print("Selection Sort Lexicographic:", selection_sort_lexicographic(arr.copy()))